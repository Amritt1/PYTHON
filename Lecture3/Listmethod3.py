# List Methods

list= [4, 2, 11]

list.append(9)
                # adds on element at the end
print(list)


list.sort()  # sorts in ascending ordr

print(list)

list.sort(reverse=True)
         # sorts in descending order

print(list)


list.reverse()
print(list)

list.insert(23, 12)
print(list)
list.pop(1)
print(list)

list.remove(11)
print(list)




